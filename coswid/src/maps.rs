/// The `resource-collection` group from [CoSWID Section 2.9.2].
///
/// This extends [`PathElementsGroup`] with `process` and `resource` fields.
///
/// ```text
/// resource-collection = (
///   path-elements-group,
///   ? process => one-or-more<process-entry>,
///   ? resource => one-or-more<resource-entry>,
///   * $$resource-collection-extension,
/// )
/// ```
///
/// Note: `resource-collection` is a CDDL group, so its fields are flattened
/// into the containing map (`payload-entry`, `evidence-entry`). This struct
/// provides a standalone representation of the group.
