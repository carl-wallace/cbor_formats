//! Map-based structs from the Concise Software Identification Tags (CoSWID) spec ([RFC 9393]).
//!
//! This module implements the following CDDL productions:
//!
//! | CDDL | Rust |
//! |------|------|
//! | `concise-swid-tag` | [`ConciseSwidTag`] / [`ConciseSwidTagCbor`] |
//! | `entity-entry` | [`EntityEntry`] / [`EntityEntryCbor`] |
//! | `file-entry` | [`FileEntry`] / [`FileEntryCbor`] |
//! | `directory-entry` | [`DirectoryEntry`] / [`DirectoryEntryCbor`] |
//! | `link-entry` | [`LinkEntry`] / [`LinkEntryCbor`] |
//! | `payload-entry` | [`PayloadEntry`] / [`PayloadEntryCbor`] |
//! | `evidence-entry` | [`EvidenceEntry`] / [`EvidenceEntryCbor`] |
//! | `process-entry` | [`ProcessEntry`] / [`ProcessEntryCbor`] |
//! | `resource-entry` | [`ResourceEntry`] / [`ResourceEntryCbor`] |
//! | `software-meta-entry` | [`SoftwareMetaEntry`] / [`SoftwareMetaEntryCbor`] |
//! | `path-elements-group` | [`PathElementsGroup`] / [`PathElementsGroupCbor`] |
//! | `resource-collection` | [`ResourceCollection`] / [`ResourceCollectionCbor`] |
//!
//! Each struct has a companion `*Cbor` type generated by the
//! [`StructToMap`] macro for direct CBOR map serialization.
//!
//! [RFC 9393]: https://datatracker.ietf.org/doc/html/rfc9393

